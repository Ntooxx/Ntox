import { describe, it, expect, vi, afterEach } from "vitest";
import { createTelegramImageSender, createWhatsAppImageSender } from "./media-send.js";

const PNG_DATA_URL = `data:image/png;base64,${Buffer.from("png-bytes").toString("base64")}`;

interface RecordedCall {
  url: string;
  init?: RequestInit;
}

function stubFetch(handler: (url: string, init?: RequestInit) => Response | Promise<Response>): RecordedCall[] {
  const calls: RecordedCall[] = [];
  vi.stubGlobal(
    "fetch",
    vi.fn(async (input: RequestInfo | URL, init?: RequestInit) => {
      const url = String(input);
      calls.push({ url, init });
      return handler(url, init);
    }),
  );
  return calls;
}

afterEach(() => {
  vi.unstubAllGlobals();
});

describe("createTelegramImageSender", () => {
  it("uploads the decoded image as multipart sendPhoto with the caption", async () => {
    const calls = stubFetch(() => new Response(JSON.stringify({ ok: true }), { status: 200 }));

    await createTelegramImageSender("TOK")("555", PNG_DATA_URL, "Image generated by image");

    expect(calls).toHaveLength(1);
    expect(calls[0].url).toBe("https://api.telegram.org/botTOK/sendPhoto");
    const form = calls[0].init?.body as FormData;
    expect(form.get("chat_id")).toBe("555");
    expect(form.get("caption")).toBe("Image generated by image");
    const photo = form.get("photo") as Blob;
    expect(photo.type).toBe("image/png");
    expect(await photo.text()).toBe("png-bytes");
  });

  it("surfaces HTTP failures as errors", async () => {
    stubFetch(() => new Response("nope", { status: 400 }));
    await expect(createTelegramImageSender("TOK")("555", PNG_DATA_URL, "")).rejects.toThrow(
      "Telegram sendPhoto failed (400)",
    );
  });

  it("rejects payloads that are not images", async () => {
    stubFetch(() => new Response("{}", { status: 200 }));
    await expect(createTelegramImageSender("TOK")("555", "data:text/plain;base64,aGk=", "")).rejects.toThrow(
      "unsupported image payload",
    );
    await expect(createTelegramImageSender("TOK")("555", "not a data url", "")).rejects.toThrow(
      "unsupported image payload",
    );
  });
});

describe("createWhatsAppImageSender", () => {
  it("uploads media first, then sends the image message", async () => {
    const calls = stubFetch((url) => {
      if (url.endsWith("/PN1/media")) return new Response(JSON.stringify({ id: "IMG_UP" }), { status: 200 });
      return new Response(JSON.stringify({ success: true }), { status: 200 });
    });

    await createWhatsAppImageSender("TOK", "PN1")("15551234567", PNG_DATA_URL, "chart for you");

    expect(calls).toHaveLength(2);
    expect(calls[0].url).toBe("https://graph.facebook.com/v18.0/PN1/media");
    const uploadForm = calls[0].init?.body as FormData;
    expect(uploadForm.get("type")).toBe("image/png");
    expect(uploadForm.get("messaging_product")).toBe("whatsapp");
    expect(calls[1].url).toBe("https://graph.facebook.com/v18.0/PN1/messages");
    const body = JSON.parse(String(calls[1].init?.body)) as {
      type: string;
      to: string;
      image: { id: string; caption?: string };
    };
    expect(body.type).toBe("image");
    expect(body.to).toBe("15551234567");
    expect(body.image.id).toBe("IMG_UP");
    expect(body.image.caption).toBe("chart for you");
  });

  it("omits the caption when there is none", async () => {
    const calls = stubFetch((url) => {
      if (url.endsWith("/PN1/media")) return new Response(JSON.stringify({ id: "IMG_UP" }), { status: 200 });
      return new Response(JSON.stringify({ success: true }), { status: 200 });
    });

    await createWhatsAppImageSender("TOK", "PN1")("15551234567", PNG_DATA_URL, "");

    const body = JSON.parse(String(calls[1].init?.body)) as { image: { caption?: string } };
    expect(body.image).toEqual({ id: "IMG_UP" });
  });

  it("fails when the upload returns no media id", async () => {
    stubFetch(() => new Response(JSON.stringify({}), { status: 200 }));
    await expect(createWhatsAppImageSender("TOK", "PN1")("1555", PNG_DATA_URL, "")).rejects.toThrow("no id");
  });

  it("fails when the upload HTTP status is bad", async () => {
    stubFetch(() => new Response("denied", { status: 401 }));
    await expect(createWhatsAppImageSender("TOK", "PN1")("1555", PNG_DATA_URL, "")).rejects.toThrow(
      "WhatsApp media upload failed (401)",
    );
  });
});
